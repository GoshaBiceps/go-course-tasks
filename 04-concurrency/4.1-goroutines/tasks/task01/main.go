// Задание: Параллельная обработка задач (goroutines + WaitGroup)
//
// Есть список задач (числа от 1 до 10).
// Запускаем каждую задачу в отдельной горутине.
//
// Каждая горутина:
//   1. Ждёт случайное время 50–200 мс
//   2. Выводит: "Задача N выполнена за Xms"
//
// В конце:
//   - ждём все горутины через WaitGroup
//   - выводим: "Все 10 задач выполнены!"

package main

import (
	"fmt"
	"math/rand"
	"sync"
	"time"
)

func main() {
	// создаём WaitGroup для ожидания всех горутин
	var wg sync.WaitGroup

	for i := 1; i <= 10; i++ {
		// увеличиваем счётчик горутин
		wg.Add(1)

		// запускаем горутину и передаём i (чтобы не было проблемы замыкания)
		go func(i int) {
			// уменьшаем счётчик при завершении
			defer wg.Done()

			// генерируем случайную задержку 50–200 мс
			delay := rand.Intn(150) + 50

			// "работа" — спим
			time.Sleep(time.Duration(delay) * time.Millisecond)

			// вывод результата
			fmt.Printf("Задача %d выполнена за %dms\n", i, delay)

		}(i)
	}

	// ждём завершения всех горутин
	wg.Wait()

	// финальное сообщение
	fmt.Println("Все 10 задач выполнены!")
}
